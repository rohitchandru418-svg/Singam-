/**
 * Action form specifications.
 *
 * Each named action declares the fields its form shows. The form component renders them
 * generically, so a new workflow step needs only a spec here.
 */

export type FieldType =
  | "text"
  | "textarea"
  | "number"
  | "scale"
  | "money"
  | "date"
  | "select"
  | "checkbox"
  | "user"
  | "status"
  | "json";

export interface FieldSpec {
  name: string;
  label: string;
  type: FieldType;
  required?: boolean;
  hint?: string;
  options?: { value: string; label: string }[];
  statusRegistry?: string;
  defaultValue?: string | number | boolean;
  placeholder?: string;
  /** A `*_type` column whose value selects which records the paired id column can point at. */
  linkTypeFor?: string;
  /** For a `scale` field: the slider bounds and step (max defaults to 10). */
  scaleMax?: number;
  scaleMin?: number;
  scaleStep?: number;
  /** A `scale` criterion the SOP lets a reviewer mark "not applicable" for a stage. */
  skippable?: boolean;
}

