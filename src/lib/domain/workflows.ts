import type { Department } from "./departments";

/**
 * Process foundation.
 *
 * The SOPs supplied by the business are modelled here as declarative stage
 * definitions. Every stage carries the six things the brief requires:
 *
 *   owner -> deadline -> required output -> evidence -> approver -> escalation
 *
 * Stage definitions drive the UI (journey maps), the task generator
 * (`src/lib/server/tasks.ts`) and the deadline engine (`domain/workingDays.ts`).
 */

export interface StageDefinition {
  key: string;
  label: string;
  journey: JourneyKey;
  order: number;
  department: Department;
  ownerRole: string;
  /** Deadline expressed in working days from the stage's start event. */
  deadline?: { workingDays: number; fromEvent: string };
  requiredOutput: string;
  evidence: string;
  approverRole?: string;
  /** Document records that must exist before the stage can be completed. */
  requiredDocuments?: string[];
  escalation?: string;
  statusRegistry?: string;
  module?: string;
  notes?: string;
}

export type JourneyKey =
  | "startup"
  | "investor"
  | "content"
  | "investment"
  | "finance"
  | "community";

export interface JourneyMeta {
  key: JourneyKey;
  label: string;
  description: string;
  department: Department;
}

